import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const recipeDir = path.join(rootDir, 'recipe');
const docsDir = path.join(rootDir, 'docs');
const imagesDir = path.join(docsDir, 'images');
const outJsPath = path.join(docsDir, 'bundled-recipes.js');
const outManifestPath = path.join(docsDir, 'recipes-manifest.json');
const stampHtml = process.argv.includes('--stamp-html');

// Identical algorithm to computeRecipesHash() in docs/index.html
function computeRecipesHash(items) {
    if (!Array.isArray(items) || items.length === 0) return '0:0:0000000000000000';
    const sorted = [...items]
        .filter(it => it && it.path && typeof it.content === 'string')
        .sort((a, b) => (a.path < b.path ? -1 : (a.path > b.path ? 1 : 0)));
    let h1 = 0x811c9dc5;
    let h2 = 0x01000193;
    let totalLen = 0;
    for (let idx = 0; idx < sorted.length; idx++) {
        const chunk = sorted[idx].path + '\n' + sorted[idx].content.replace(/\r\n/g, '\n');
        totalLen += chunk.length;
        for (let i = 0; i < chunk.length; i++) {
            const c = chunk.charCodeAt(i);
            h1 ^= c;
            h1 = Math.imul(h1, 0x01000193);
            h2 ^= (c + i);
            h2 = Math.imul(h2, 0x85ebca6b);
        }
    }
    const hex1 = (h1 >>> 0).toString(16).padStart(8, '0');
    const hex2 = (h2 >>> 0).toString(16).padStart(8, '0');
    return `${sorted.length}:${totalLen}:${hex1}${hex2}`;
}

function collectMarkdownFiles(dir, baseDir = rootDir) {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    let results = [];
    for (const entry of entries) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            results = results.concat(collectMarkdownFiles(fullPath, baseDir));
        } else if (entry.isFile() && entry.name.endsWith('.md')) {
            const relPath = path.relative(baseDir, fullPath).split(path.sep).join('/');
            const content = fs.readFileSync(fullPath, 'utf8').replace(/\r\n/g, '\n');
            results.push({ path: relPath, content });
        }
    }
    return results;
}

function collectImageHashes(dir, baseDir = docsDir) {
    if (!fs.existsSync(dir)) return {};
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    const hashes = {};
    for (const entry of entries) {
        const fullPath = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            Object.assign(hashes, collectImageHashes(fullPath, baseDir));
        } else if (entry.isFile() && /\.(?:jpg|jpeg|png|webp|svg|gif)$/i.test(entry.name)) {
            const relPath = path.relative(baseDir, fullPath).split(path.sep).join('/');
            const buf = fs.readFileSync(fullPath);
            hashes[relPath] = crypto.createHash('sha1').update(buf).digest('hex').slice(0, 10);
        }
    }
    return Object.fromEntries(Object.entries(hashes).sort(([a], [b]) => a.localeCompare(b)));
}

const bundled = fs.existsSync(recipeDir) ? collectMarkdownFiles(recipeDir) : [];
bundled.sort((a, b) => a.path.localeCompare(b.path));

const contentHash = computeRecipesHash(bundled);
const imageHashes = collectImageHashes(imagesDir);
const nowIso = new Date().toISOString();
const versionStamp = Date.now().toString(36);

const jsOutput = `// Auto-generated by scripts/bundle-recipes.mjs — DO NOT EDIT MANUALLY
window.BUNDLED_AT = ${JSON.stringify(nowIso)};
window.BUNDLED_HASH = ${JSON.stringify(contentHash)};
window.BUNDLED_IMAGE_HASHES = ${JSON.stringify(imageHashes, null, 2)};
window.BUNDLED_RECIPES = ${JSON.stringify(bundled, null, 2)};
`;

fs.writeFileSync(outJsPath, jsOutput, 'utf8');

const manifestPayload = {
    generatedAt: nowIso,
    contentHash,
    imageHashes,
    items: bundled
};
fs.writeFileSync(outManifestPath, JSON.stringify(manifestPayload, null, 2) + '\n', 'utf8');

if (stampHtml) {
    const indexHtmlPath = path.join(docsDir, 'index.html');
    if (fs.existsSync(indexHtmlPath)) {
        const html = fs.readFileSync(indexHtmlPath, 'utf8');
        const updatedHtml = html.replace(
            /<script src="\.\/bundled-recipes\.js(?:\?v=[^"]*)?"><\/script>/,
            `<script src="./bundled-recipes.js?v=${versionStamp}"></script>`
        );
        if (updatedHtml !== html) {
            fs.writeFileSync(indexHtmlPath, updatedHtml, 'utf8');
        }
    }
}

console.log(`Bundled ${bundled.length} recipe(s) & ${Object.keys(imageHashes).length} image hash(es) (hash=${contentHash})`);
